//! UI copy for the desktop app: English by default, neutral Argentine Spanish (es-AR) like the
//! web app. Strings live here, not in the views, so they are reviewed and tested in one place.

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Locale {
    #[default]
    En,
    EsAr,
}

impl Locale {
    /// Picks a locale from a `LANG`-style value (`es_AR.UTF-8`, `en_US`, ...). Anything that is
    /// not Spanish is English.
    pub fn detect(value: &str) -> Self {
        let lang = value.trim().to_ascii_lowercase();
        if lang == "es"
            || lang.starts_with("es_")
            || lang.starts_with("es-")
            || lang.starts_with("es.")
        {
            Self::EsAr
        } else {
            Self::En
        }
    }
}

pub fn amount_label(locale: Locale, cents: i64, currency: &str) -> String {
    let separator = if locale == Locale::EsAr { "," } else { "." };
    let sign = if cents < 0 { "−" } else { "" };
    let cents = cents.unsigned_abs();
    format!(
        "{sign}{}{separator}{:02} {currency}",
        cents / 100,
        cents % 100
    )
}

pub fn receipt_status_label(locale: Locale, status: &str) -> &str {
    let key = match status {
        "open" => Key::SalesStatusOpen,
        "paid" => Key::SalesStatusPaid,
        "void" => Key::SalesStatusVoid,
        "refunded" => Key::SalesStatusRefunded,
        "partially_refunded" => Key::SalesStatusPartiallyRefunded,
        _ => return status,
    };
    t(locale, key)
}

/// Replaces `{name}` placeholders.
pub fn fill(template: &str, args: &[(&str, &str)]) -> String {
    args.iter().fold(template.to_owned(), |acc, (name, value)| {
        acc.replace(&format!("{{{name}}}"), value)
    })
}

